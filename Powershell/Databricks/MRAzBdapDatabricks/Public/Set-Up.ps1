# #REQUIRES -Version 5.0
# #REQUIRES #-Modules
# #REQUIRES #-RunAsAdministrator

function Set-Up {

    <#
    .SYNOPSIS
    Create the component by naming convention <Company><Application><Environment>

    .DESCRIPTION
    <Company><Application><Environment>
    Naming patterns <Company>, <Application>, <Environment>, .

    Examples:
    -

    .EXAMPLE
    C:\PS>New-Component -ComponentName
    Example of how to use this cmdlet

    .EXAMPLE
    C:\PS>New-Component -Company 'mr' -Application 'bdap' -Environment 'test' -Location 'we' -Component 'test' -Descriptor '666'
    Example of how to use this cmdlet

    .PARAMETER Company
    Name of Company - e.g. MR

    .PARAMETER Application
    Name of Application - e.g. BDAP

    .PARAMETER Environment
    Name of Environment - e.g. SBX [ValidateSet("prd", "int", "dev", "sbx", "tt")]

     .PARAMETER MrLocation
    Name of MrLocation - e.g. we (Get-MrAzBdapSharedLocation -Loation $Location)

    .PARAMETER Descriptor
    Descriptor if needed, incremental value or description

    .PARAMETER Delimiter
    Delimiter if needed, Default "-"


    .PARAMETER PricingTier
    The pricing tier of workspace



    .PARAMETER ComponentName
    Component Name - e.g. mr-bdap-sbx-eu-shared001
    Can be generated by using Get-MrAzBdap<Module>Name
    Uses ParameterSet ComponentName

    .PARAMETER ResourceGroupName
    Resource Group Name - e.g. <Company>-<Application>-<Environment>-<Location>-<Component>[-<Description or Incremental Number>]

    .PARAMETER Location
    Name of Azure Location - e.g. West Europe
    [ValidateScript( { (Get-AzLocation).Location -contains $_ } )]

    .PARAMETER WhatIf
    Dry run of script, returns theoretical values

    .PARAMETER Confirm
    Before impacting system ask to confirm
    #>

    [CmdletBinding(SupportsShouldProcess)]
    [OutputType([PSCustomObject])]
    param(
        [Parameter(
            Mandatory = $true,
            ValueFromPipelineByPropertyName = $true,
            HelpMessage = "Configuration object",
            ParameterSetName = 'Config')]
        [PSCustomObject] $Config,

        [Parameter(
            Mandatory = $true,
            ValueFromPipelineByPropertyName = $true,
            HelpMessage = "Path to a configuration object",
            ParameterSetName = 'ConfigPath')
        ]
        [String] $configPath
    )

    begin {
        $VerbosePreference = "Continue"
    }

    process {
        if (-not ([String]::IsNullOrEmpty($configPath))) {
            if (-not (Test-Path -Path $configPath)) {
                throw "ConfigPath '$configPath' doesn't exist."
            }
            else {
                $Config = (Get-Content -Raw $configPath) | ConvertFrom-Json
                Write-Verbose "[$(Get-Date)] Config loaded"
            }
        }

        Write-Verbose "##################"
        Write-Verbose "# 1 - PARAMETERS #"
        Write-Verbose "##################"
        Write-Verbose "[$(Get-Date)]=========="
        Write-Verbose "[$(Get-Date)] $Config"
        Write-Verbose "[$(Get-Date)]=========="

        Write-Verbose "############"
        Write-Verbose "# 2 - TAGS #"
        Write-Verbose "############"

        # Gather Release.Name & currentModule.Version and set in ARM template
        if ($env:RELEASE_RELEASENAME) { $ReleaseIdentifier = $env:RELEASE_RELEASENAME }
        else { $ReleaseIdentifier = "UnknownReleaseIdentifier" }
        Write-Verbose "Determined release name: $ReleaseIdentifier"

        $currentModuleName = (Split-Path (Split-Path $PSScriptRoot -Parent) -Leaf)
        $DeploymentModuleVersion = (Get-Module $currentModuleName).Version
        Write-Verbose "Determined module version: $DeploymentModuleVersion"


        Write-Verbose "#############"
        Write-Verbose "# 3 - Pre Deployment  #"
        Write-Verbose "#############"

        #  Get component name i.e workspace name .
        $DeligationInputObjectComponent = @{
            privatesubnet     = $Config.customPrivateSubnetName
            publicsubnet      = $Config.customPublicSubnetName
            Vnetname          = $Config.VnetName
            Vnetresoursegroup = $Config.VnetResourceGroupName
        }

        $ServiceepInputObjectComponent = @{
            privatesubnet     = $Config.customPrivateSubnetName
            publicsubnet      = $Config.customPublicSubnetName
            Vnetname          = $Config.VnetName
            Vnetresoursegroup = $Config.VnetResourceGroupName
            Nsg               = $Config.NSG
            nsgRg             = $Config.ResourceGroupName
        }

        Set-Subnetdelegation @DeligationInputObjectComponent -Verbose
        Set-SubnetEndpoints  @ServiceepInputObjectComponent -Verbose

        Write-Verbose "#############"
        Write-Verbose "# 4 - SETUP #"
        Write-Verbose "#############"

        $MrLocation = Get-MRAzBdapSharedLocation -Location $config.Location

        Write-Verbose "MrLocation: $MrLocation"


        $InputObjectComponent = @{ Company = $Config.Company
            Application                    = $Config.Application
            Environment                    = $Config.Environment
            MrLocation                     = $MrLocation
            Descriptor                     = $Config.Descriptor
        }
        #gent name
        $ComponentName = Get-MRAzBdapDatabricksName @InputObjectComponent -Verbose
        Write-Verbose "Component Name: $ComponentName"

        # Create Resourse group if it do not  exist and get name

        if ([string]::IsNullOrEmpty($Config.ResourceGroupName)) {
            $resourceGroupParam = @{
                Company     = $Config.Company
                Application = $Config.Application
                Environment = $Config.Environment
                Location    = $Config.Location
                MrLocation  = $Config.MrLocation
                Component   = $Config.Component
                Descriptor  = $Config.Descriptor
            }
            #  Get component name i.e workspace name .
            $ResourceGroup = New-MRAzBdapResourceGroupComponent @resourceGroupParam
            Write-Verbose -Message ("[$(Get-Date)] created ResourceGroup {0}" -f $ResourceGroup.ResourceGroupName)

            $Config.ResourceGroupName = $ResourceGroup.ResourceGroupName
        }

        # Get vnet Id , as Databrick template expect full vnet id .

        $Vnet = Get-AzVirtualNetwork -Name $Config.vnetName -ResourceGroupName $Config.VnetResourceGroupName -ErrorAction Stop
        $customVirtualNetworkId = $Vnet.Id
        Write-Verbose "Vnet ID : $customVirtualNetworkId"

        try {

            $InputObject = @{
                ComponentName                   = $ComponentName
                ResourceGroupName               = $Config.ResourceGroupName
                ManagedResourceGroupName        = $Config.managedResourceGroupName
                LogAnalyticsResourceGroupName   = $Config.LogAnalyticsResourceGroupName
                LogAnalyticsWorkspaceName       = $Config.LogAnalyticsWorkspaceName
                #Descriptor                = $Config.Descriptor
                customVirtualNetworkId          = $customVirtualNetworkId
                customPrivateSubnetName         = $Config.customPrivateSubnetName
                customPublicSubnetName          = $Config.customPublicSubnetName
                VirtualNetworkResourceGroupName = $Config.VnetResourceGroupName
                PricingTier                     = $Config.pricingTier
                Location                        = $MrLocation
                DeploymentModuleVersion         = $DeploymentModuleVersion
                ReleaseIdentifier               = $ReleaseIdentifier
            }

            Write-Verbose "New-Component"

            if ($PSCmdlet.ShouldProcess(("databricks {0}" -f $ComponentName), "Deploy")) {
                $templateOutput = New-MRAzBdapDatabricksComponent @InputObject -Verbose
                Write-Verbose "ARM Template Output: $templateOutput"
            }
            else {
                New-MRAzBdapDatabricksComponent @InputObject -Verbose -WhatIf
            }

            Write-Verbose "#############"
            Write-Verbose "# 4 - Post Deployment steps : 1 . Add dignostic settings for databricks ( log analytics ) #"
            Write-Verbose "#############"

            $LogAnalyticsObjectComponent = @{
                LogAnalyticsWorkspaceName     = $Config.LogAnalyticsWorkspaceName
                LogAnalyticsResourceGroupName = $Config.LogAnalyticsResourceGroupName
                DatabricksWorkspaceName       = $ComponentName
                ResourceGroupName             = $Config.ResourceGroupName

            }

            Set-LogAnalyticsWorkspace @LogAnalyticsObjectComponent -Verbose

        }
        catch [Exception] {
            Write-Error "$($_.Exception) found"
            Write-Verbose "$($_.ScriptStackTrace)"
            throw $_
        }
    }
}