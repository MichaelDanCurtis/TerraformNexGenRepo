function New-Component {
    <#
    .SYNOPSIS
    Create the component by naming convention <Company><Application><Environment>

    .DESCRIPTION
    <Company><Application><Environment>
    Naming patterns <Company>, <Application>, <Environment>, .

    Examples:
    -

    .EXAMPLE
    C:\PS>New-Component -ComponentName
    Example of how to use this cmdlet

    .EXAMPLE
    C:\PS>New-Component -Company 'mr' -Application 'bdap' -Environment 'test' -Location 'we' -Component 'test' -Descriptor '666'
    Example of how to use this cmdlet

    .PARAMETER Company
    Name of Company - e.g. MR

    .PARAMETER Application
    Name of Application - e.g. BDAP

    .PARAMETER Environment
    Name of Environment - e.g. SBX [ValidateSet("prd", "int", "dev", "sbx", "tt")]

     .PARAMETER MrLocation
    Name of MrLocation - e.g. we (Get-MrAzBdapSharedLocation -Loation $Location)

    .PARAMETER Descriptor
    Descriptor if needed, incremental value or description

    .PARAMETER Delimiter
    Delimiter if needed, Default "-"


    .PARAMETER PricingTier
    The pricing tier of workspace



    .PARAMETER ComponentName
    Component Name - e.g. mr-bdap-sbx-eu-shared001
    Can be generated by using Get-MrAzBdap<Module>Name
    Uses ParameterSet ComponentName

    .PARAMETER ResourceGroupName
    Resource Group Name - e.g. <Company>-<Application>-<Environment>-<Location>-<Component>[-<Description or Incremental Number>]

    .PARAMETER Location
    Name of Azure Location - e.g. West Europe
    [ValidateScript( { (Get-AzLocation).Location -contains $_ } )]

    .PARAMETER WhatIf
    Dry run of script, returns theoretical values

    .PARAMETER Confirm
    Before impacting system ask to confirm
    #>


    [CmdletBinding(
        SupportsShouldProcess = $True,
        PositionalBinding = $True,
        DefaultParameterSetName = "Default"
    )]

    [OutputType([PSCustomObject])]
    param(
        [Parameter(
            Mandatory = $true,
            ValueFromPipelineByPropertyName = $true,
            ParameterSetName = 'ComponentName',
            HelpMessage = "Component Name - e.g. MRBDAP"
        )]
        [string]
        $ComponentName,
        [Parameter(
            Mandatory = $true,
            ValueFromPipelineByPropertyName = $true,
            HelpMessage = "Resource Group Name - e.g. <Company>-<Application>-<Environment>-<Location>-<Component>[-<Description or Incremental Number>]"
        )]
        [string]
        $ResourceGroupName,
        [Parameter(
            Mandatory = $true,
            ValueFromPipelineByPropertyName = $true,
            HelpMessage = "DB managed Resource Group Name - e.g. <Company>-<Application>-<Environment>-<Location>-<Component>[-<Description or Incremental Number>]"
        )]
        [string]
        $ManagedResourceGroupName,
        [Parameter(
            Mandatory = $true,
            ValueFromPipelineByPropertyName = $true,
            HelpMessage = "LogAnalyticsResourceGroupName - e.g. <Company>-<Application>-<Environment>-<Location>-<Component>[-<Description or Incremental Number>]"
        )]
        [string]
        $LogAnalyticsResourceGroupName,
        [Parameter(
            Mandatory = $true,
            ValueFromPipelineByPropertyName = $true,
            HelpMessage = "LogAnalyticsWorkspaceName - e.g. <Company>-<Application>-<Environment>-<Location>-<Component>[-<Description or Incremental Number>]"
        )]
        [string]
        $LogAnalyticsWorkspaceName,

        [Parameter(
            Mandatory = $false,
            HelpMessage = "Name of the virtual network name."
        )]
        [string] $customVirtualNetworkId,

        [Parameter(
            Mandatory = $false,
            HelpMessage = "The name of the private subnet in the custom VNet."
        )]
        [string] $customPrivateSubnetName,

        [Parameter(
            Mandatory = $false,
            HelpMessage = "The name of the public subnet in the custom VNet."
        )]
        [string] $customPublicSubnetName,

        [Parameter(
            Mandatory = $false,
            HelpMessage = "The name of the public subnet in the custom VNet."
        )]
        [string] $VirtualNetworkResourceGroupName,

        [Parameter(
            Mandatory = $false,
            HelpMessage = "The pricing tier of workspace"
        )]
        [ValidateSet("standard",
            "premium")]
        [string] $PricingTier = "premium",

        [Parameter(
            Mandatory = $true,
            ValueFromPipelineByPropertyName = $true,
            HelpMessage = "Name of Azure Location - e.g. West Europe"
        )]
        # [ValidateScript( { (Get-AzLocation).Location -contains $_ } )]
        # [Alias("Loc")]
        [string] $Location,
        [Parameter(
            Mandatory = $false,
            HelpMessage = "The name of deployment Module Version"
        )]
        [string] $DeploymentModuleVersion,
        [Parameter(
            Mandatory = $false,
            HelpMessage = "The name of deployment Module Version"
        )]
        [string] $ReleaseIdentifier
    )

    begin {


        Write-Verbose "Deploying databricks workpspace with vnet injection"
        $templatePath = '\Static\Advanced\azuredeploy.json'


        $TemplateUri = Get-MrAzBdapDatabricksArmTemplate -Path $templatePath -Source "Local" -ErrorAction Stop
        if (!$TemplateUri) {
            Throw "Missing template file. Deployment has stopped"
        }

    }

    process {

        #if ([string]::IsNullOrEmpty($ComponentName)) {
        # $ComponentName = Get-MRAzBdapDatabricksName -Company $Company -Application $Application -Environment $Environment -MrLocation $MrLocation -Descriptor $Descriptor -ErrorAction Stop
        #}
        Write-Verbose "[$(Get-Date)] ComponentName $ComponentName"

        #$ResourceGroup = Get-AzResourceGroup $ResourceGroupName -ErrorAction Stop
        # Write-Verbose "[$(Get-Date)] ResourceGroup $($ResourceGroup.ResourceGroupName)"

        $TemplateParameterObject = @{
            workspaceName = $ComponentName
            pricingTier   = $PricingTier
        }

        Write-Verbose "[$(Get-Date)] Advanced configuration"



        Write-Verbose "[$(Get-Date)] Vnet $customVirtualNetworkId Public $PublicSubnetName Private $PrivateSubnetName"

        $TemplateParameterObject += @{
            customVirtualNetworkId   = $customVirtualNetworkId
            customPublicSubnetName   = $customPublicSubnetName
            customPrivateSubnetName  = $customPrivateSubnetName
            managedResourceGroupName = $managedResourceGroupName
            DeploymentModuleVersion  = $DeploymentModuleVersion
            ReleaseIdentifier        = $ReleaseIdentifier
        }

        try {

            if ($PSCmdlet.ShouldProcess($ResourceGroupName, $ComponentName)) {

                $Deployment = New-AzResourceGroupDeployment -ResourceGroupName $ResourceGroupName -TemplateUri $TemplateUri -TemplateParameterObject $TemplateParameterObject -ErrorVariable ErrorMessages
                #az group deployment create -g $ResourceGroupName  --template-file $TemplateUri --parameters $TemplateParameterObject
                if ($ErrorMessages) {
                    Write-Output '', 'Template deployment returned the following errors:', @(@($ErrorMessages) | ForEach-Object { $_.Exception.Message.TrimEnd("`r`n") })
                }
                else {
                    $return = Get-DeploymentOutput $Deployment.Outputs
                }

            }
            else {
                $Deployment = Test-AzResourceGroupDeployment -ResourceGroupName $ResourceGroupName -TemplateUri $TemplateUri -TemplateParameterObject $TemplateParameterObject

                $return = [PSCustomObject]@{
                    'ComponentName'     = $ComponentName
                    'ResourceGroupName' = $ResourceGroupName
                }
            }

            $return
        }
        catch [Exception] {
            Write-Error "$($_.Exception) found"
            Write-Verbose "$($_.ScriptStackTrace)"
            throw $_
        }
    }

    end {
    }
}

