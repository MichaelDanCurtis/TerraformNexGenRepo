#REQUIRES -Version 5.0
#REQUIRES #-Modules
#REQUIRES #-RunAsAdministrator

function New-Component {
    <#
    .SYNOPSIS
    Create the component by naming convention <Company><Application><Environment>

    .DESCRIPTION
    <Company><Application><Environment>
    Naming patterns <Company>, <Application>, <Environment>, .

    .PARAMETER Company
    Name of Company - e.g. MR

    .PARAMETER Application
    Name of Application - e.g. BDAP

    .PARAMETER Environment
    Name of Environment - e.g. SBX [ValidateSet("prd", "int", "dev", "sbx", "tt")]

    .PARAMETER Description
    Name of Description - e.g. e1000

    .PARAMETER MrLocation
    Name of abbreviated Location - e.g. eus2 (length: 2-4 letters)

    .PARAMETER ReaderGroup
    Name of AD Reade rGroup - e.g. Fun-CED-bdap-sbx-azure-reader

    .PARAMETER ContributorGroup
   Name of AD Contibutor Group - e.g. Fun-CED-bdap-sbx-azure-contributor

    .PARAMETER Delimiter
    Delimiter if needed, Default "-"

    .PARAMETER ComponentName
    Component Name - e.g. mr-bdap-sbx-eu-shared001
    Can be generated by using Get-MrAzBdapAdfName
    Uses ParameterSet ComponentName

    .PARAMETER ResourceGroupName
    Resource Group Name - e.g. <Company>-<Application>-<Environment>-<Location>-<Component>[-<Description or Incremental Number>]

    .PARAMETER Location
    Name of Azure Location - e.g. West Europe
    [ValidateScript( { (Get-AzLocation).Location -contains $_ } )]

    .PARAMETER LogAnalyticsWorkspace
    Name of Log Analytics workspace

    .PARAMETER NumberOfAzIRs
    Number of Azure Hosted Integrated Runtimes associated with ADF

    .PARAMETER WhatIf
    Dry run of script, returns theoretical values

    .PARAMETER Confirm
    Before impacting system ask to confirm

    .PARAMETER DeploymentModuleVersion
    Deployed artifact version

    .PARAMETER ReleaseIdentifier
    Identifier of the used deployment pipeline

    .EXAMPLE
    C:\PS>New-Component -ComponentName
    Example of how to use this cmdlet

    .EXAMPLE
    C:\PS>New-Component -Company 'mr' -Application 'bdap' -Environment 'test' -Location 'we' -Component 'test' -Descriptor '666'
    Example of how to use this cmdlet
    #>


    [CmdletBinding(
        SupportsShouldProcess = $True,
        PositionalBinding = $True,
        DefaultParameterSetName = "Default"
    )]
    [OutputType([System.Collections.Hashtable])]
    param(
        [Parameter(
            Mandatory = $true,
            ParameterSetName = 'Default',
            HelpMessage = "Name of Description - e.g. ADF-e000"
        )]
        [Alias("De")]
        [string] $Description,

        [Parameter(
            Mandatory = $true,
            ParameterSetName = 'Default',
            HelpMessage = "Name of Company - e.g. MR"
        )]
        [Alias("Co")]
        [string] $Company,

        [Parameter(
            Mandatory = $true,
            ParameterSetName = 'Default',
            HelpMessage = "Name of Application - e.g. BDAP"
        )]
        [Alias("App")]
        [string] $Application,

        [Parameter(
            Mandatory = $true,
            ParameterSetName = 'Default',
            HelpMessage = "Name of Environment - e.g. SBX"
        )]
        [ValidateSet("prd", "int", "dev", "sbx", "tt", "prp", "inp", "dep", "sbp")]
        [Alias("Env")]
        [string] $Environment,

        [Parameter(
            Mandatory = $true,
            ParameterSetName = 'Default',
            HelpMessage = "Name of Mr Location - e.g. WE"
        )]
        [ValidateLength(2, 4)]
        [Alias("MRLoc")]
        [string] $MrLocation,

        [Parameter(
            Mandatory = $false,
            ParameterSetName = 'Default',
            HelpMessage = "Delimiter if needed"
        )]
        [string]
        [ValidatePattern("(\-|\s)")] # matches dash or space
        [ValidateLength(1, 1)]
        $Delimiter = "",

        [Parameter(
            Mandatory = $true,
            HelpMessage = "Name of Log Analytics Workspace"
        )]
        [Alias("Log")]
        [string] $LogAnalyticsWorkspace,

        [Parameter(
            Mandatory = $false,
            ParameterSetName = 'ComponentName',
            HelpMessage = "Component Name "
        )]
        [string]
        $ComponentName = "",

        [Parameter(
            Mandatory = $true,
            ValueFromPipelineByPropertyName = $true,
            HelpMessage = "Resource Group Name - e.g. <Company>-<Application>-<Environment>-<Location>-<Description or Incremental Number>"
        )]
        [string]
        $ResourceGroupName,

        [Parameter(
            Mandatory = $true,
            ValueFromPipelineByPropertyName = $true,
            HelpMessage = "Name of Azure Location - e.g. West Europe"
        )]
        [ValidateScript( { (Get-AzLocation).Location -contains $_ } )]
        [Alias("Loc")]
        [string] $Location,

        [Parameter(
            Mandatory = $true,
            ValueFromPipelineByPropertyName = $true,
            HelpMessage = "Number of Azure Integration Runtimes"
        )]
        [string] $NumberOfAzIRs,

        [Parameter(Mandatory = $false)]
        [string] $DeploymentModuleVersion = "UnknownDeploymentVersion",

        [Parameter(Mandatory = $false)]
        [string] $ReleaseIdentifier = "UnknownReleaseIdentifier"
    )

    begin {

    }

    process {

        $TemplateUri = Get-MrAzBdapAdfArmTemplate

        if ([string]::IsNullOrEmpty($ComponentName)) {
            $ComponentName = Get-MrAzBdapAdfName -Company $Company -Application $Application -Environment $Environment -MrLocation $MrLocation  -Description $Description
        }
        Write-Verbose "[$(Get-Date)] ComponentName $ComponentName"

        $TemplateParameterObject = @{
            DataFactoryName = $ComponentName
        }

        $DeploymentObject = @{
            ResourceGroupName       = $ResourceGroupName
            TemplateUri             = $TemplateUri
            TemplateParameterObject = $TemplateParameterObject
            ErrorVariable           = 'ErrorMessages'
            DeploymentModuleVersion = $DeploymentModuleVersion
            ReleaseIdentifier       = $ReleaseIdentifier
        }

        if ($PSCmdlet.ShouldProcess($ResourceGroupName, $ComponentName)) {

            $Deployment = New-AzResourceGroupDeployment @DeploymentObject
            Write-Verbose "Get deployment output"
            $DeploymentOutput = Get-MRAzBdapSharedDeploymentOutput  -Deployment $Deployment -ErrorMessage $ErrorMessages
            $DatafactoryId = $DeploymentOutput.dF_resourceId
        }
        else {
            return $DeploymentObject
        }

        Write-Verbose "[$(Get-Date)] Object ID for Data Factory: $DatafactoryId"
        Start-Sleep -s 15
        $principalid = (Get-AzDataFactoryV2 -ResourceGroupName $ResourceGroupName -Name $ComponentName).identity.PrincipalId
        Write-Verbose "[$(Get-Date)] Object ID for Access Policy: $principalid"


        if ($PSCmdlet.ShouldProcess($ResourceGroupName, $ComponentName)) {

            if ($Environment -ne 'TT') {
                Set-AzKeyVaultAccessPolicy -VaultName $ComponentName -ObjectID $principalid -PermissionsToSecrets Get, Set
            }

            Set-Diagnostic -ResourceId $DatafactoryId -LogAnalyticsWorkspace $LogAnalyticsWorkspace

            Set-AzHostedIR -ResourceGroupName $ResourceGroupName -DataFactoryName $ComponentName -Location $Location -NumberOfAzIRs $NumberOfAzIRs

        }

        return $DeploymentOutput

    }

    end {
    }

}

function Set-Diagnostic {

    [CmdletBinding(SupportsShouldProcess = $True)]
    param (
        [Parameter(
            Mandatory = $true
        )]
        [string]$ResourceId,

        [Parameter(
            Mandatory = $true
        )]
        [string]$LogAnalyticsWorkspace
    )

    process {

        Write-Verbose "[$(Get-Date)] Resource dId::  $ResourceId"

        $DiagnosticInputObject = @{
            ResourceId    = $ResourceId
            WorkspaceName = $LogAnalyticsWorkspace
            Categories    = @("ActivityRuns", "PipelineRuns", "TriggerRuns")
            Metrics       = @("AllMetrics")
        }
        if ($PSCmdlet.ShouldProcess($ResourceId)) {
            Set-MrAzBdapSharedDiagnostic @DiagnosticInputObject
        }

    }

}
